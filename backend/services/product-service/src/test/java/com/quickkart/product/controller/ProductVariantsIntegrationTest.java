package com.quickkart.product.controller;

import com.quickkart.product.security.JwtService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.transaction.annotation.Transactional;

import java.util.UUID;

import static org.hamcrest.Matchers.hasItem;
import static org.hamcrest.Matchers.hasSize;
import static org.hamcrest.Matchers.not;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.patch;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.put;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/** Sizes and colours: admins set them per product, stock is the total, and shoppers can filter by size. */
@SpringBootTest
@AutoConfigureMockMvc
@Transactional
class ProductVariantsIntegrationTest {

    @Autowired MockMvc mvc;
    @Autowired JdbcTemplate jdbc;
    @Autowired JwtService jwt;

    String admin;
    String category;

    @BeforeEach
    void setUp() throws Exception {
        jdbc.execute("create table if not exists users (id bigint generated by default as identity primary key, name varchar(255), password varchar(255), email varchar(255), role varchar(255), email_verified boolean, account_status varchar(255), password_changed_at timestamp)");
        String email = "admin-" + UUID.randomUUID() + "@example.invalid";
        jdbc.update("insert into users(email,name,role,email_verified,account_status) values (?,?,?,true,'ACTIVE')", email, "Shop Admin", "ADMIN");
        Long id = jdbc.queryForObject("select id from users where email=?", Long.class, email);
        admin = "Bearer " + jwt.generateToken(email, "ADMIN", id);
        category = "Tees " + UUID.randomUUID().toString().substring(0, 8);
        mvc.perform(post("/api/admin/categories").header("Authorization", admin).contentType(MediaType.APPLICATION_JSON)
                .content("{\"name\":\"" + category + "\",\"imageUrl\":\"/categories/all.webp\"}")).andExpect(status().isCreated());
    }

    private String product(String name, String variants) {
        return "{\"name\":\"" + name + "\",\"price\":799,\"stockQuantity\":0,\"category\":\"" + category + "\""
                + (variants == null ? "" : ",\"variants\":" + variants) + "}";
    }

    private Long create(String name, String variants) throws Exception {
        String body = mvc.perform(post("/api/admin/products").header("Authorization", admin).contentType(MediaType.APPLICATION_JSON)
                        .content(product(name, variants)))
                .andExpect(status().isCreated())
                .andReturn().getResponse().getContentAsString();
        return Long.valueOf(body.replaceFirst(".*?\"id\":(\\d+).*", "$1"));
    }

    @Test
    void stockIsTheTotalOfTheSizesAndTheCustomerSeesEachSize() throws Exception {
        String name = "Heavy tee " + UUID.randomUUID();
        Long id = create(name, "[{\"size\":\"M\",\"color\":\"Black\",\"stockQuantity\":4},{\"size\":\"L\",\"color\":\"Black\",\"stockQuantity\":0}]");
        mvc.perform(get("/api/products/" + id))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.stockQuantity").value(4))
                .andExpect(jsonPath("$.variants", hasSize(2)))
                .andExpect(jsonPath("$.variants[?(@.size=='M')].stockQuantity", hasItem(4)))
                .andExpect(jsonPath("$.variants[?(@.size=='L')].stockQuantity", hasItem(0)));
    }

    @Test
    void editingSizesUpdatesInPlaceAndKeepsLeftOutSizesAtZero() throws Exception {
        Long id = create("Edit tee " + UUID.randomUUID(), "[{\"size\":\"M\",\"stockQuantity\":4},{\"size\":\"L\",\"stockQuantity\":2}]");
        mvc.perform(put("/api/admin/products/" + id).header("Authorization", admin).contentType(MediaType.APPLICATION_JSON)
                        .content(product("Edit tee renamed", "[{\"size\":\"M\",\"stockQuantity\":9},{\"size\":\"XL\",\"stockQuantity\":1}]")))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.stockQuantity").value(10))
                .andExpect(jsonPath("$.variants", hasSize(3)))
                .andExpect(jsonPath("$.variants[?(@.size=='L')].stockQuantity", hasItem(0))); // kept: carts/orders may point at it
        mvc.perform(get("/api/admin/products/" + id + "/stock-movements").header("Authorization", admin))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.content[0].reason").value("ADMIN_EDIT"));
    }

    @Test
    void duplicateOrInvalidSizesAreRejected() throws Exception {
        mvc.perform(post("/api/admin/products").header("Authorization", admin).contentType(MediaType.APPLICATION_JSON)
                        .content(product("Dup tee", "[{\"size\":\"M\",\"stockQuantity\":1},{\"size\":\"m\",\"stockQuantity\":2}]")))
                .andExpect(status().isBadRequest());
        mvc.perform(post("/api/admin/products").header("Authorization", admin).contentType(MediaType.APPLICATION_JSON)
                        .content(product("Neg tee", "[{\"size\":\"M\",\"stockQuantity\":-1}]")))
                .andExpect(status().isBadRequest());
        mvc.perform(post("/api/admin/products").header("Authorization", admin).contentType(MediaType.APPLICATION_JSON)
                        .content(product("Blank tee", "[{\"size\":\" \",\"stockQuantity\":1}]")))
                .andExpect(status().isBadRequest());
    }

    @Test
    void productStockCannotBeAdjustedDirectlyWhenItHasSizes() throws Exception {
        Long id = create("Locked tee " + UUID.randomUUID(), "[{\"size\":\"M\",\"stockQuantity\":4}]");
        mvc.perform(patch("/api/admin/products/" + id + "/stock").header("Authorization", admin).contentType(MediaType.APPLICATION_JSON)
                        .content("{\"adjustment\":5}"))
                .andExpect(status().isBadRequest());
    }

    @Test
    void shoppersCanFilterBySizeAndOnlySeeSizesInStock() throws Exception {
        String unique = "filtertee" + UUID.randomUUID().toString().substring(0, 8);
        Long medium = create(unique + " medium", "[{\"size\":\"M\",\"color\":\"Navy\",\"stockQuantity\":3}]");
        Long soldOutLarge = create(unique + " large", "[{\"size\":\"L\",\"color\":\"Navy\",\"stockQuantity\":0}]");
        Long plain = create(unique + " plain", null);

        mvc.perform(get("/api/products").param("q", unique).param("variantSize", "m"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.content[*].id", hasItem(medium.intValue())))
                .andExpect(jsonPath("$.content[*].id", not(hasItem(soldOutLarge.intValue()))))
                .andExpect(jsonPath("$.content[*].id", not(hasItem(plain.intValue()))));
        mvc.perform(get("/api/products").param("q", unique).param("variantSize", "L"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.content", hasSize(0))); // the only L is sold out
        mvc.perform(get("/api/products").param("q", unique).param("color", "navy"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.content", hasSize(1)));
    }

    @Test
    void retiredProductsLeaveTheAdminListUnlessAskedFor() throws Exception {
        String name = "Retired tee " + UUID.randomUUID();
        Long id = create(name, null);
        mvc.perform(put("/api/admin/products/" + id).header("Authorization", admin).contentType(MediaType.APPLICATION_JSON)
                        .content(product(name, null).replace("}", ",\"availability\":\"DISCONTINUED\"}")))
                .andExpect(status().isOk());
        mvc.perform(get("/api/admin/products").param("q", name).header("Authorization", admin))
                .andExpect(status().isOk()).andExpect(jsonPath("$.totalElements").value(0));
        mvc.perform(get("/api/admin/products").param("q", name).param("stock", "RETIRED").header("Authorization", admin))
                .andExpect(status().isOk()).andExpect(jsonPath("$.totalElements").value(1));
    }
}
