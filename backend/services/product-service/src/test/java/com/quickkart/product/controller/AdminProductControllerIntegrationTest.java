package com.quickkart.product.controller;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.quickkart.product.dto.ProductRequest;
import com.quickkart.product.entity.Product;
import com.quickkart.product.repository.ProductRepository;
import com.quickkart.product.security.JwtService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.delete;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.put;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

@SpringBootTest
@AutoConfigureMockMvc
@Transactional
class AdminProductControllerIntegrationTest {
    @Autowired private org.springframework.jdbc.core.JdbcTemplate securityJdbc;
    private String securityToken(String email, String role, Long id) {
        securityJdbc.execute("create table if not exists users (id bigint generated by default as identity primary key, name varchar(255), password varchar(255), email varchar(255), role varchar(255), email_verified boolean, account_status varchar(255))");
        securityJdbc.update("insert into users(email,role,email_verified,account_status) values (?,?,true,'ACTIVE')",email,role);
        Long actualId=securityJdbc.queryForObject("select id from users where email=? fetch first 1 row only",Long.class,email);
        return jwtService.generateToken(email,role,actualId);
    }


    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private ObjectMapper objectMapper;

    @Autowired
    private ProductRepository productRepository;

    @Autowired
    private JwtService jwtService;

    private String adminToken;
    private String userToken;
    private Product sampleProduct;

    @BeforeEach
    void setUp() {
        adminToken = securityToken("admin@quickkart.com", "ADMIN", 1L);
        userToken = securityToken("user@quickkart.com", "USER", 2L);

        sampleProduct = productRepository.save(new Product(
                "Sample Admin Product " + System.currentTimeMillis(),
                "Initial description",
                new BigDecimal("450.00"),
                15,
                "Electronics"
        ));
    }

    @Test
    @DisplayName("1. Admin can successfully create a new product (201 Created)")
    void testAdminCanCreateProduct() throws Exception {
        ProductRequest request = new ProductRequest(
                "Gaming Laptop Ultra",
                "High performance RTX GPU laptop",
                new BigDecimal("1499.99"),
                10,
                "Computers"
        );

        mockMvc.perform(post("/api/admin/products")
                        .header("Authorization", "Bearer " + adminToken)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(request)))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.id").exists())
                .andExpect(jsonPath("$.name").value("Gaming Laptop Ultra"))
                .andExpect(jsonPath("$.price").value(1499.99))
                .andExpect(jsonPath("$.stockQuantity").value(10));
    }

    @Test
    @DisplayName("2. Admin can successfully update an existing product (200 OK)")
    void testAdminCanUpdateProduct() throws Exception {
        ProductRequest updateRequest = new ProductRequest(
                "Updated Admin Product Name",
                "Updated detailed description",
                new BigDecimal("499.99"),
                25,
                "Electronics"
        );

        mockMvc.perform(put("/api/admin/products/" + sampleProduct.getId())
                        .header("Authorization", "Bearer " + adminToken)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(updateRequest)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.name").value("Updated Admin Product Name"))
                .andExpect(jsonPath("$.price").value(499.99))
                .andExpect(jsonPath("$.stockQuantity").value(25));

        Product updated = productRepository.findById(sampleProduct.getId()).orElseThrow();
        assertEquals("Updated Admin Product Name", updated.getName());
    }

    @Test
    @DisplayName("3. Admin can successfully delete a product (204 No Content)")
    void testAdminCanDeleteProduct() throws Exception {
        Product toDelete = productRepository.save(new Product(
                "Delete Candidate",
                "To be deleted",
                new BigDecimal("29.99"),
                5,
                "Misc"
        ));

        mockMvc.perform(delete("/api/admin/products/" + toDelete.getId())
                        .header("Authorization", "Bearer " + adminToken))
                .andExpect(status().isNoContent());

        assertFalse(productRepository.existsById(toDelete.getId()));
    }

    @Test
    @DisplayName("4. Regular USER receives 403 Forbidden on Admin Product endpoints")
    void testUserCannotAccessAdminProductApis() throws Exception {
        ProductRequest request = new ProductRequest(
                "Unauthorized Product",
                "Should fail",
                new BigDecimal("100.00"),
                5,
                "Electronics"
        );

        mockMvc.perform(post("/api/admin/products")
                        .header("Authorization", "Bearer " + userToken)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(request)))
                .andExpect(status().isForbidden())
                .andExpect(jsonPath("$.status").value(403));

        mockMvc.perform(put("/api/admin/products/" + sampleProduct.getId())
                        .header("Authorization", "Bearer " + userToken)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(request)))
                .andExpect(status().isForbidden())
                .andExpect(jsonPath("$.status").value(403));

        mockMvc.perform(delete("/api/admin/products/" + sampleProduct.getId())
                        .header("Authorization", "Bearer " + userToken))
                .andExpect(status().isForbidden())
                .andExpect(jsonPath("$.status").value(403));
    }

    @Test
    @DisplayName("5. Unauthenticated request receives 401 Unauthorized on Admin Product endpoints")
    void testUnauthenticatedUserCannotAccessAdminProductApis() throws Exception {
        ProductRequest request = new ProductRequest(
                "Unauthenticated Product",
                "Should fail",
                new BigDecimal("100.00"),
                5,
                "Electronics"
        );

        mockMvc.perform(post("/api/admin/products")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(request)))
                .andExpect(status().isUnauthorized())
                .andExpect(jsonPath("$.status").value(401));

        mockMvc.perform(put("/api/admin/products/" + sampleProduct.getId())
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(request)))
                .andExpect(status().isUnauthorized())
                .andExpect(jsonPath("$.status").value(401));

        mockMvc.perform(delete("/api/admin/products/" + sampleProduct.getId()))
                .andExpect(status().isUnauthorized())
                .andExpect(jsonPath("$.status").value(401));
    }

    @Test
    @DisplayName("Admin restock increases stock and flips OUT_OF_STOCK back to IN_STOCK")
    void adminCanRestock() throws Exception {
        Product p = productRepository.saveAndFlush(new Product("Restock me", "d", new BigDecimal("9.99"), 0, "Test"));
        p.setAvailability("OUT_OF_STOCK");
        productRepository.saveAndFlush(p);
        mockMvc.perform(org.springframework.test.web.servlet.request.MockMvcRequestBuilders.patch("/api/admin/products/" + p.getId() + "/stock")
                        .header("Authorization", "Bearer " + adminToken)
                        .contentType(MediaType.APPLICATION_JSON).content("{\"adjustment\":7}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.stockQuantity").value(7))
                .andExpect(jsonPath("$.availability").value("IN_STOCK"));
    }

    @Test
    @DisplayName("Stock can never go negative and zero adjustment is rejected")
    void stockCannotGoNegative() throws Exception {
        Product p = productRepository.saveAndFlush(new Product("Low", "d", new BigDecimal("1.00"), 2, "Test"));
        for (String body : new String[]{"{\"adjustment\":-3}", "{\"adjustment\":0}", "{}"}) {
            mockMvc.perform(org.springframework.test.web.servlet.request.MockMvcRequestBuilders.patch("/api/admin/products/" + p.getId() + "/stock")
                            .header("Authorization", "Bearer " + adminToken)
                            .contentType(MediaType.APPLICATION_JSON).content(body))
                    .andExpect(status().isBadRequest());
        }
        assertEquals(2, productRepository.findById(p.getId()).orElseThrow().getStockQuantity());
    }

    @Test
    @DisplayName("Customers cannot adjust stock")
    void customerCannotAdjustStock() throws Exception {
        Product p = productRepository.saveAndFlush(new Product("Guarded", "d", new BigDecimal("1.00"), 2, "Test"));
        mockMvc.perform(org.springframework.test.web.servlet.request.MockMvcRequestBuilders.patch("/api/admin/products/" + p.getId() + "/stock")
                        .header("Authorization", "Bearer " + userToken)
                        .contentType(MediaType.APPLICATION_JSON).content("{\"adjustment\":100}"))
                .andExpect(status().isForbidden());
        assertEquals(2, productRepository.findById(p.getId()).orElseThrow().getStockQuantity());
    }
}
