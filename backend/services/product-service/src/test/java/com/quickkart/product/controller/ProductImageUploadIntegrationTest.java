package com.quickkart.product.controller;

import com.quickkart.product.entity.Product;
import com.quickkart.product.repository.ProductRepository;
import com.quickkart.product.security.JwtService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.mock.web.MockMultipartFile;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.web.servlet.MockMvc;

import java.math.BigDecimal;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.*;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.multipart;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

@SpringBootTest
@AutoConfigureMockMvc
class ProductImageUploadIntegrationTest {

    @TempDir static Path uploads;

    @DynamicPropertySource
    static void uploadDir(DynamicPropertyRegistry r) {
        r.add("app.uploads.dir", () -> uploads.toString());
    }

    private static final byte[] PNG = {(byte) 0x89, 'P', 'N', 'G', 0x0D, 0x0A, 0x1A, 0x0A, 0, 0, 0, 13, 'I', 'H', 'D', 'R'};
    private static final byte[] JPEG = {(byte) 0xFF, (byte) 0xD8, (byte) 0xFF, (byte) 0xE0, 0, 16, 'J', 'F', 'I', 'F'};

    @Autowired MockMvc mvc;
    @Autowired ProductRepository products;
    @Autowired JwtService jwt;
    @Autowired JdbcTemplate jdbc;

    private Product product;
    private String admin;
    private String user;

    private String token(String email, String role) {
        jdbc.execute("create table if not exists users (id bigint generated by default as identity primary key, name varchar(255), password varchar(255), email varchar(255), role varchar(255), email_verified boolean, account_status varchar(255), password_changed_at timestamp)");
        jdbc.update("insert into users(email,role,email_verified,account_status) values (?,?,true,'ACTIVE')", email, role);
        Long id = jdbc.queryForObject("select max(id) from users where email=?", Long.class, email);
        return jwt.generateToken(email, role, id);
    }

    @BeforeEach
    void setUp() {
        long n = System.nanoTime();
        admin = token("img-admin-" + n + "@quickkart.com", "ADMIN");
        user = token("img-user-" + n + "@quickkart.com", "USER");
        product = products.save(new Product("Upload Kettle " + n, "d", new BigDecimal("999.00"), 5, "Shoes"));
    }

    @Test
    void adminUploadsAPhotoThatIsServedPubliclyAndReplacesTheOldOne() throws Exception {
        String first = mvc.perform(multipart("/api/admin/products/{id}/image", product.getId())
                        .file(new MockMultipartFile("file", "kettle.png", "image/png", PNG))
                        .header("Authorization", "Bearer " + admin))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.imageUrl").value(org.hamcrest.Matchers.matchesPattern("/api/products/images/[0-9a-f-]{36}\\.png")))
                .andReturn().getResponse().getContentAsString();
        String firstUrl = com.jayway.jsonpath.JsonPath.read(first, "$.imageUrl");

        mvc.perform(get(firstUrl))
                .andExpect(status().isOk())
                .andExpect(header().string("Content-Type", "image/png"))
                .andExpect(header().string("X-Content-Type-Options", "nosniff"))
                .andExpect(content().bytes(PNG));

        String second = mvc.perform(multipart("/api/admin/products/{id}/image", product.getId())
                        .file(new MockMultipartFile("file", "kettle.jpg", "image/jpeg", JPEG))
                        .header("Authorization", "Bearer " + admin))
                .andExpect(status().isOk())
                .andReturn().getResponse().getContentAsString();
        assertTrue(com.jayway.jsonpath.JsonPath.<String>read(second, "$.imageUrl").endsWith(".jpg"));
        mvc.perform(get(firstUrl)).andExpect(status().isNotFound());
        try (var files = Files.list(uploads.resolve("products"))) {
            assertEquals(1, files.count(), "only the current photo is left on disk; the replaced one is deleted");
        }
    }

    @Test
    void aFileThatIsNotReallyAnImageIsRejectedWhateverItsNameSays() throws Exception {
        byte[] html = "<html><script>alert(1)</script></html>".getBytes();
        mvc.perform(multipart("/api/admin/products/{id}/image", product.getId())
                        .file(new MockMultipartFile("file", "photo.jpg", "image/jpeg", html))
                        .header("Authorization", "Bearer " + admin))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.message").value("Only JPEG, PNG or WebP images are allowed."));
    }

    @Test
    void customersCannotUploadAndPathTricksFindNothing() throws Exception {
        mvc.perform(multipart("/api/admin/products/{id}/image", product.getId())
                        .file(new MockMultipartFile("file", "x.png", "image/png", PNG))
                        .header("Authorization", "Bearer " + user))
                .andExpect(status().isForbidden());
        mvc.perform(get("/api/products/images/..%2F..%2Fapplication.properties")).andExpect(status().is4xxClientError());
        mvc.perform(get("/api/products/images/not-a-uuid.png")).andExpect(status().isNotFound());
    }
}
