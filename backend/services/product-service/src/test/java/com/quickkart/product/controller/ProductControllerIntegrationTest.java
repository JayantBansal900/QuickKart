package com.quickkart.product.controller;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.quickkart.product.dto.ProductRequest;
import com.quickkart.product.entity.Product;
import com.quickkart.product.repository.ProductRepository;
import com.quickkart.product.security.JwtService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;

import static org.hamcrest.Matchers.greaterThanOrEqualTo;
import static org.hamcrest.Matchers.hasSize;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

@SpringBootTest
@AutoConfigureMockMvc
@Transactional
class ProductControllerIntegrationTest {
    @Autowired private org.springframework.jdbc.core.JdbcTemplate securityJdbc;
    private String securityToken(String email, String role, Long id) {
        securityJdbc.execute("create table if not exists users (id bigint generated by default as identity primary key, name varchar(255), password varchar(255), email varchar(255), role varchar(255), email_verified boolean, account_status varchar(255), password_changed_at timestamp)");
        securityJdbc.update("insert into users(email,role,email_verified,account_status) values (?,?,true,'ACTIVE')",email,role);
        Long actualId=securityJdbc.queryForObject("select id from users where email=? fetch first 1 row only",Long.class,email);
        return jwtService.generateToken(email,role,actualId);
    }


    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private ObjectMapper objectMapper;

    @Autowired
    private ProductRepository productRepository;

    @Autowired
    private JwtService jwtService;

    private Product testProduct;
    private String adminToken;
    private String userToken;

    @BeforeEach
    void setUp() {
        testProduct = productRepository.save(new Product(
                "Controller Test Phone " + System.currentTimeMillis(),
                "High performance smartphone",
                new BigDecimal("699.99"),
                20,
                "Jackets"
        ));

        adminToken = securityToken("admin@quickkart.com", "ADMIN", 1L);
        userToken = securityToken("user@quickkart.com", "USER", 2L);
    }

    @Test
    @DisplayName("1. Public GET /api/products returns 200 OK and a page of products")
    void testGetAllProducts() throws Exception {
        mockMvc.perform(get("/api/products"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.content", hasSize(greaterThanOrEqualTo(1))))
                .andExpect(jsonPath("$.totalElements").exists());
    }

    @Test
    @DisplayName("2. Public GET /api/products/{id} returns 200 OK with correct product details")
    void testGetProductById() throws Exception {
        mockMvc.perform(get("/api/products/" + testProduct.getId()))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.id").value(testProduct.getId()))
                .andExpect(jsonPath("$.name").value(testProduct.getName()))
                .andExpect(jsonPath("$.price").value(testProduct.getPrice().doubleValue()));
    }

    @Test
    @DisplayName("3. GET /api/products/{id} for non-existent product returns 404 Not Found")
    void testGetProductNotFound() throws Exception {
        mockMvc.perform(get("/api/products/999999"))
                .andExpect(status().isNotFound())
                .andExpect(jsonPath("$.status").value(404))
                .andExpect(jsonPath("$.message").exists());
    }

    @Test
    @DisplayName("4. POST /api/admin/products with blank name returns 400 Bad Request")
    void testValidationBlankName() throws Exception {
        ProductRequest invalidRequest = new ProductRequest(
                "",
                "Description with blank name",
                new BigDecimal("100.00"),
                10,
                "Jackets"
        );

        mockMvc.perform(post("/api/admin/products")
                        .header("Authorization", "Bearer " + adminToken)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(invalidRequest)))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.status").value(400))
                .andExpect(jsonPath("$.errors.name").exists());
    }

    @Test
    @DisplayName("5. POST /api/admin/products with negative price returns 400 Bad Request")
    void testValidationNegativePrice() throws Exception {
        ProductRequest invalidRequest = new ProductRequest(
                "Negative Price Gadget",
                "Description",
                new BigDecimal("-25.00"),
                10,
                "Jackets"
        );

        mockMvc.perform(post("/api/admin/products")
                        .header("Authorization", "Bearer " + adminToken)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(invalidRequest)))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.status").value(400))
                .andExpect(jsonPath("$.errors.price").exists());
    }
}
