package com.quickkart.product.controller;

import com.quickkart.product.entity.Product;
import com.quickkart.product.repository.ProductRepository;
import com.quickkart.product.security.JwtService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;
import java.util.UUID;

import static org.hamcrest.Matchers.hasItem;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.delete;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.patch;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.put;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/** Categories, reviews, stock history and the paged admin catalog. */
@SpringBootTest
@AutoConfigureMockMvc
@Transactional
class CatalogFeaturesIntegrationTest {

    @Autowired MockMvc mvc;
    @Autowired JdbcTemplate jdbc;
    @Autowired JwtService jwt;
    @Autowired ProductRepository products;

    String admin;
    String customer;
    Long customerId;
    Product kettle;

    @BeforeEach
    void setUp() {
        jdbc.execute("create table if not exists users (id bigint generated by default as identity primary key, name varchar(255), password varchar(255), email varchar(255), role varchar(255), email_verified boolean, account_status varchar(255), password_changed_at timestamp)");
        jdbc.execute("create table if not exists orders (id bigint generated by default as identity primary key, user_id bigint, status varchar(40))");
        jdbc.execute("create table if not exists order_items (id bigint generated by default as identity primary key, order_id bigint, product_id bigint)");
        admin = token("admin-" + UUID.randomUUID() + "@example.invalid", "ADMIN", "Shop Admin");
        String email = "buyer-" + UUID.randomUUID() + "@example.invalid";
        customer = token(email, "USER", "Priya Sharma");
        customerId = jdbc.queryForObject("select id from users where email=?", Long.class, email);
        Product p = new Product("Review Kettle " + UUID.randomUUID(), "d", new BigDecimal("999.00"), 3, "Shoes");
        p.setRating(4.0);
        p.setReviewCount(4);
        kettle = products.saveAndFlush(p);
    }

    private String token(String email, String role, String name) {
        jdbc.update("insert into users(email,name,role,email_verified,account_status) values (?,?,?,true,'ACTIVE')", email, name, role);
        Long id = jdbc.queryForObject("select id from users where email=?", Long.class, email);
        return "Bearer " + jwt.generateToken(email, role, id);
    }

    private void deliver(Long productId) {
        jdbc.update("insert into orders(user_id,status) values (?, 'DELIVERED')", customerId);
        Long orderId = jdbc.queryForObject("select max(id) from orders", Long.class);
        jdbc.update("insert into order_items(order_id,product_id) values (?,?)", orderId, productId);
    }

    @Test
    void categoriesAreListedAndManagedByAdmins() throws Exception {
        mvc.perform(get("/api/categories"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$[*].name", hasItem("Clothing")))
                .andExpect(jsonPath("$[?(@.name=='Shoes')].key", hasItem("SHOES")));

        String body = "{\"name\":\"Toys & Games\",\"description\":\"Fun\",\"imageUrl\":\"/categories/all.webp\"}";
        mvc.perform(post("/api/admin/categories").header("Authorization", customer).contentType(MediaType.APPLICATION_JSON).content(body))
                .andExpect(status().isForbidden());
        mvc.perform(post("/api/admin/categories").header("Authorization", admin).contentType(MediaType.APPLICATION_JSON).content(body))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.key").value("TOYS & GAMES"));
        mvc.perform(post("/api/admin/categories").header("Authorization", admin).contentType(MediaType.APPLICATION_JSON).content(body.replace("Toys", "toys")))
                .andExpect(status().isConflict());
        mvc.perform(post("/api/admin/categories").header("Authorization", admin).contentType(MediaType.APPLICATION_JSON)
                        .content("{\"name\":\"Bad\",\"imageUrl\":\"javascript:alert(1)\"}"))
                .andExpect(status().isBadRequest());

        Long id = jdbc.queryForObject("select id from categories where name='Toys & Games'", Long.class);
        Product toy = products.saveAndFlush(new Product("Puzzle " + UUID.randomUUID(), "d", new BigDecimal("10.00"), 5, "Toys & Games"));
        mvc.perform(put("/api/admin/categories/" + id).header("Authorization", admin).contentType(MediaType.APPLICATION_JSON)
                        .content("{\"name\":\"Toys\",\"active\":false}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.active").value(false));
        assertEquals("Toys", jdbc.queryForObject("select category from products where id=?", String.class, toy.getId()));
        mvc.perform(get("/api/categories")).andExpect(jsonPath("$[?(@.name=='Toys')]").isEmpty());
        // Hidden category: its products leave search and the category counts too.
        mvc.perform(get("/api/products").param("q", toy.getName().toLowerCase()))
                .andExpect(jsonPath("$.totalElements").value(0));
        mvc.perform(get("/api/products/categories")).andExpect(jsonPath("$[?(@.category=='TOYS')]").isEmpty());
        mvc.perform(put("/api/admin/categories/" + id).header("Authorization", admin).contentType(MediaType.APPLICATION_JSON)
                        .content("{\"name\":\"Toys\",\"active\":true}"))
                .andExpect(status().isOk());
        mvc.perform(get("/api/products").param("q", toy.getName().toLowerCase()))
                .andExpect(jsonPath("$.totalElements").value(1));

        mvc.perform(delete("/api/admin/categories/" + id).header("Authorization", admin)).andExpect(status().isConflict());
        products.delete(toy);
        products.flush();
        mvc.perform(delete("/api/admin/categories/" + id).header("Authorization", admin)).andExpect(status().isNoContent());
    }

    @Test
    void onlyCustomersWhoReceivedTheProductCanReview() throws Exception {
        String url = "/api/products/" + kettle.getId() + "/reviews";
        mvc.perform(get(url + "/eligibility").header("Authorization", customer))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.canReview").value(false));
        mvc.perform(post(url).header("Authorization", customer).contentType(MediaType.APPLICATION_JSON).content("{\"rating\":5}"))
                .andExpect(status().isForbidden());
        mvc.perform(post(url).contentType(MediaType.APPLICATION_JSON).content("{\"rating\":5}"))
                .andExpect(status().isUnauthorized());

        deliver(kettle.getId());
        mvc.perform(post(url).header("Authorization", customer).contentType(MediaType.APPLICATION_JSON).content("{\"rating\":9}"))
                .andExpect(status().isBadRequest());
        mvc.perform(post(url).header("Authorization", customer).contentType(MediaType.APPLICATION_JSON)
                        .content("{\"rating\":5,\"title\":\"Boils fast\",\"comment\":\"Great kettle\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.authorName").value("Priya S."))
                .andExpect(jsonPath("$.verifiedPurchase").value(true));
        Product after = products.findById(kettle.getId()).orElseThrow();
        assertEquals(5, after.getReviewCount());
        assertEquals(4.2, after.getRating(), 0.001);

        // Writing again edits the same review instead of adding a second one.
        mvc.perform(post(url).header("Authorization", customer).contentType(MediaType.APPLICATION_JSON).content("{\"rating\":1}"))
                .andExpect(status().isOk());
        after = products.findById(kettle.getId()).orElseThrow();
        assertEquals(5, after.getReviewCount());
        assertEquals(3.4, after.getRating(), 0.001);

        mvc.perform(get(url)).andExpect(status().isOk())
                .andExpect(jsonPath("$.totalElements").value(1))
                .andExpect(jsonPath("$.content[0].mine").value(false));
        mvc.perform(get(url).header("Authorization", customer))
                .andExpect(jsonPath("$.content[0].mine").value(true));

        Long reviewId = jdbc.queryForObject("select id from product_reviews where product_id=?", Long.class, kettle.getId());
        mvc.perform(delete(url + "/" + reviewId).header("Authorization", admin.replace("x", "x")))
                .andExpect(status().isNotFound()); // admins moderate through /api/admin, not as the author
        mvc.perform(delete(url + "/" + reviewId).header("Authorization", customer)).andExpect(status().isNoContent());
        after = products.findById(kettle.getId()).orElseThrow();
        assertEquals(4, after.getReviewCount());
        assertEquals(4.0, after.getRating(), 0.001);
    }

    @Test
    void adminCatalogIsPagedFilteredAndStockChangesAreRecorded() throws Exception {
        mvc.perform(get("/api/admin/products").param("stock", "LOW").param("q", kettle.getName()).header("Authorization", admin))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.content[0].id").value(kettle.getId()))
                .andExpect(jsonPath("$.totalElements").value(1));
        products.saveAndFlush(new Product("Second " + UUID.randomUUID(), "d", new BigDecimal("5.00"), 50, "Books"));
        products.saveAndFlush(new Product("Third " + UUID.randomUUID(), "d", new BigDecimal("5.00"), 50, "Books"));
        mvc.perform(get("/api/admin/products").param("size", "2").header("Authorization", admin))
                .andExpect(jsonPath("$.content.length()").value(2))
                .andExpect(jsonPath("$.size").value(2));

        mvc.perform(patch("/api/admin/products/" + kettle.getId() + "/stock").header("Authorization", admin)
                        .contentType(MediaType.APPLICATION_JSON).content("{\"adjustment\":7}"))
                .andExpect(status().isOk());
        mvc.perform(get("/api/admin/products/" + kettle.getId() + "/stock-movements").header("Authorization", admin))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.content[0].change").value(7))
                .andExpect(jsonPath("$.content[0].stockAfter").value(10))
                .andExpect(jsonPath("$.content[0].reason").value("RESTOCK"));
        mvc.perform(get("/api/admin/products/" + kettle.getId() + "/stock-movements").header("Authorization", customer))
                .andExpect(status().isForbidden());
    }

    @Test
    void wishlistSavesProductsPerCustomer() throws Exception {
        mvc.perform(get("/api/wishlist")).andExpect(status().isUnauthorized());
        mvc.perform(put("/api/wishlist/" + kettle.getId()).header("Authorization", customer)).andExpect(status().isNoContent());
        mvc.perform(put("/api/wishlist/" + kettle.getId()).header("Authorization", customer)).andExpect(status().isNoContent()); // idempotent
        mvc.perform(put("/api/wishlist/999999").header("Authorization", customer)).andExpect(status().isNotFound());
        mvc.perform(get("/api/wishlist").header("Authorization", customer))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.length()").value(1))
                .andExpect(jsonPath("$[0].id").value(kettle.getId()));
        mvc.perform(get("/api/wishlist/ids").header("Authorization", admin)).andExpect(jsonPath("$.length()").value(0)); // per customer
        mvc.perform(delete("/api/wishlist/" + kettle.getId()).header("Authorization", customer)).andExpect(status().isNoContent());
        mvc.perform(get("/api/wishlist/ids").header("Authorization", customer)).andExpect(jsonPath("$.length()").value(0));
    }

    @Test
    void popularSortOrdersByReviewCount() throws Exception {
        mvc.perform(get("/api/products").param("sort", "popular").param("size", "1")).andExpect(status().isOk());
    }
}
