package com.quickkart.order.security;
import org.junit.jupiter.api.*;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import java.util.UUID;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.*;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;
@SpringBootTest
@AutoConfigureMockMvc
class AccountSecurityRegressionTest {
    @Autowired JdbcTemplate jdbc;
    @Autowired JwtService jwt;
    @Autowired MockMvc mvc;
    String email;
    Long accountId;
    @BeforeEach void setup() {
        jdbc.execute("create table if not exists users (id bigint generated by default as identity primary key, name varchar(255), email varchar(255), password varchar(255), role varchar(255))");
        jdbc.execute("alter table users add column if not exists email_verified boolean default false");
        jdbc.execute("alter table users add column if not exists account_status varchar(255) default 'PENDING_VERIFICATION'");
        email=UUID.randomUUID()+"@example.com";
        jdbc.update("insert into users (name,email,password,role,email_verified,account_status) values (?,?,?,?,?,?)","Customer",email,"hash","USER",true,"ACTIVE");
        accountId=jdbc.queryForObject("select id from users where email=?",Long.class,email);
    }
    @Test void rolesSuspensionDeletionAndVerificationAreCheckedOnEveryRequest() throws Exception {
        String token=jwt.generateToken(email,"USER",accountId);
        mvc.perform(get("/api/kafka/events").header("Authorization","Bearer "+token)).andExpect(status().isForbidden());
        mvc.perform(get("/api/orders").header("Authorization","Bearer "+token)).andExpect(status().isOk());
        mvc.perform(get("/api/admin/orders").header("Authorization","Bearer "+token)).andExpect(status().isForbidden());
        jdbc.update("update users set account_status='SUSPENDED' where email=?",email);
        mvc.perform(get("/api/admin/orders").header("Authorization","Bearer "+token)).andExpect(status().isUnauthorized());
        jdbc.update("update users set account_status='DISABLED' where email=?",email);
        mvc.perform(get("/api/admin/orders").header("Authorization","Bearer "+token)).andExpect(status().isUnauthorized());
        jdbc.update("update users set account_status='ACTIVE',email_verified=false where email=?",email);
        mvc.perform(get("/api/admin/orders").header("Authorization","Bearer "+token)).andExpect(status().isUnauthorized());
        jdbc.update("update users set email_verified=true,role='ADMIN' where email=?",email);
        mvc.perform(get("/api/admin/orders").header("Authorization","Bearer "+token)).andExpect(status().isUnauthorized());
        String admin=jwt.generateToken(email,"ADMIN",accountId);
        mvc.perform(get("/api/kafka/events").header("Authorization","Bearer "+admin)).andExpect(status().isNotFound());
        mvc.perform(get("/api/admin/orders").header("Authorization","Bearer "+admin)).andExpect(status().isOk());
        jdbc.update("delete from users where email=?",email);
        mvc.perform(get("/api/admin/orders").header("Authorization","Bearer "+admin)).andExpect(status().isUnauthorized());
        jdbc.update("insert into users(name,email,password,role,email_verified,account_status) values (?,?,?,?,?,?)","Replacement",email,"hash","ADMIN",true,"ACTIVE");
        mvc.perform(get("/api/admin/orders").header("Authorization","Bearer "+admin)).andExpect(status().isUnauthorized());
    }
    @Test void invalidJwtAndNonAdminActuatorRequestsAreRejected() throws Exception {
        mvc.perform(get("/api/admin/orders").header("Authorization","Bearer invalid.token")).andExpect(status().isUnauthorized());
        mvc.perform(get("/actuator/metrics").header("Authorization","Bearer "+jwt.generateToken(email,"USER",accountId))).andExpect(status().isForbidden());
    }
}
