-- Size / colour variants. A product with variants keeps products.stock_quantity as the TOTAL of its
-- variants, so listings, search and analytics keep working unchanged; the variant row is what a
-- customer actually buys and what checkout locks and decrements.
CREATE TABLE IF NOT EXISTS product_variants (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     BIGINT      NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    size           VARCHAR(20) NOT NULL,
    color          VARCHAR(40) NOT NULL DEFAULT '',
    sku            VARCHAR(80),
    stock_quantity INTEGER     NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    CONSTRAINT uk_product_variants_product_size_color UNIQUE (product_id, size, color)
);
CREATE INDEX IF NOT EXISTS idx_product_variants_product ON product_variants (product_id);

-- Cart lines and order lines remember which variant was chosen. NULL = a product without variants.
ALTER TABLE cart_items  ADD COLUMN IF NOT EXISTS variant_id BIGINT REFERENCES product_variants(id);
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS variant_id BIGINT REFERENCES product_variants(id);
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS size  VARCHAR(20);
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS color VARCHAR(40);

-- One line per (cart, product, variant): the same shirt in M and in L are two lines.
ALTER TABLE cart_items DROP CONSTRAINT IF EXISTS uk_cart_item_cart_product;
DROP INDEX IF EXISTS uk_cart_item_cart_product;
CREATE UNIQUE INDEX IF NOT EXISTS uk_cart_item_cart_product_variant
    ON cart_items (cart_id, product_id, COALESCE(variant_id, 0));
