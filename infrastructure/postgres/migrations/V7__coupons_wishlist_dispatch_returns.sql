-- V7: coupons, wishlist, dispatch tracking, returns and cart activity.
-- Additive only and safe to re-run. Applied by the db-migrate (Flyway) container.

-- Coupons (order-service). PERCENT takes `value` as a percentage (1-90), FLAT as rupees.
CREATE TABLE IF NOT EXISTS coupons (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               VARCHAR(40)   NOT NULL,
    description        VARCHAR(200),
    discount_type      VARCHAR(10)   NOT NULL CHECK (discount_type IN ('PERCENT', 'FLAT')),
    discount_value     NUMERIC(12,2) NOT NULL CHECK (discount_value > 0),
    max_discount       NUMERIC(12,2),
    min_order_amount   NUMERIC(12,2) NOT NULL DEFAULT 0,
    usage_limit        INTEGER,
    used_count         INTEGER       NOT NULL DEFAULT 0,
    once_per_customer  BOOLEAN       NOT NULL DEFAULT true,
    starts_at          TIMESTAMP,
    expires_at         TIMESTAMP,
    active             BOOLEAN       NOT NULL DEFAULT true,
    created_at         TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_coupons_code_upper ON coupons (UPPER(code));

INSERT INTO coupons (code, description, discount_type, discount_value, max_discount, min_order_amount, usage_limit, once_per_customer)
SELECT v.code, v.description, v.discount_type, v.discount_value, v.max_discount, v.min_order_amount, v.usage_limit, v.once_per_customer
FROM (VALUES
    ('WELCOME10', '10% off your first order (up to ₹500)', 'PERCENT', 10.00, 500.00, 0.00, NULL::INTEGER, true),
    ('FLAT200',   '₹200 off orders above ₹1,999',          'FLAT',   200.00, NULL::NUMERIC, 1999.00, NULL::INTEGER, false),
    ('BIGSALE25', '25% off orders above ₹9,999 (up to ₹2,500), first 100 orders', 'PERCENT', 25.00, 2500.00, 9999.00, 100, true)
) AS v(code, description, discount_type, discount_value, max_discount, min_order_amount, usage_limit, once_per_customer)
WHERE NOT EXISTS (SELECT 1 FROM coupons c WHERE UPPER(c.code) = UPPER(v.code));

-- Orders: discount, dispatch tracking, delivery time.
