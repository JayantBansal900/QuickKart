ALTER TABLE orders ADD COLUMN IF NOT EXISTS discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS coupon_code     VARCHAR(40);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS courier         VARCHAR(60);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS tracking_number VARCHAR(80);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS shipped_at      TIMESTAMP;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS delivered_at    TIMESTAMP;
UPDATE orders SET subtotal_amount = total_amount WHERE subtotal_amount IS NULL;
CREATE INDEX IF NOT EXISTS idx_orders_coupon ON orders (UPPER(coupon_code)) WHERE coupon_code IS NOT NULL;

-- Returns (order-service): a customer asks to return a delivered order; an admin approves or rejects.
CREATE TABLE IF NOT EXISTS order_returns (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT        NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    reason       VARCHAR(40)   NOT NULL,
    comment      VARCHAR(1000),
    status       VARCHAR(20)   NOT NULL CHECK (status IN ('REQUESTED', 'APPROVED', 'REJECTED')),
    admin_note   VARCHAR(500),
    requested_at TIMESTAMP     NOT NULL,
    resolved_at  TIMESTAMP,
    CONSTRAINT uk_order_returns_order UNIQUE (order_id)
);

-- Wishlist (product-service).
CREATE TABLE IF NOT EXISTS wishlist_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT    NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    product_id BIGINT    NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_wishlist_user_product UNIQUE (user_id, product_id)
);

-- Cart activity, for the admin "open carts" view.
ALTER TABLE carts ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP;
