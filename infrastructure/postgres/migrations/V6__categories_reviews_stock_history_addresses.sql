-- V6: category management, customer reviews, stock-change history and saved delivery addresses.
-- Additive only and safe to re-run. Applied automatically by the db-migrate (Flyway) container.

-- Categories are managed by admins (product-service). products.category keeps the category NAME,
-- so existing rows need no change; the name is matched case-insensitively.
CREATE TABLE IF NOT EXISTS categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80)   NOT NULL,
    description VARCHAR(300),
    image_url   VARCHAR(1000),
    sort_order  INTEGER       NOT NULL DEFAULT 0,
    active      BOOLEAN       NOT NULL DEFAULT true,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_categories_name_upper ON categories (UPPER(name));

