-- One review per customer per product, only for products they received (enforced by product-service).
CREATE TABLE IF NOT EXISTS product_reviews (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT        NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    user_id    BIGINT        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    rating     INTEGER       NOT NULL CHECK (rating BETWEEN 1 AND 5),
    title      VARCHAR(120),
    comment    VARCHAR(2000),
    created_at TIMESTAMP     NOT NULL,
    updated_at TIMESTAMP     NOT NULL,
    CONSTRAINT uk_product_reviews_product_user UNIQUE (product_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_product_reviews_product ON product_reviews (product_id, created_at DESC);

-- Every stock change: checkout (-), cancellation (+), admin restock/correction (+/-).
CREATE TABLE IF NOT EXISTS stock_movements (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      BIGINT       NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    change_quantity INTEGER      NOT NULL,
    stock_after     INTEGER      NOT NULL,
    reason          VARCHAR(40)  NOT NULL,
    reference       VARCHAR(120),
    actor           VARCHAR(255),
    created_at      TIMESTAMP    NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_stock_movements_product ON stock_movements (product_id, id DESC);

-- Saved delivery address (the name and phone already live on users).
ALTER TABLE users ADD COLUMN IF NOT EXISTS saved_address VARCHAR(1000);

-- Analytics and admin order list.
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON orders (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders (status);
