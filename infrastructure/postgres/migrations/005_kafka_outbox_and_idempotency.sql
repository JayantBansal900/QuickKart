-- 005: reliable order events.
--   outbox_events    : written by order-service in the checkout transaction; published by OutboxRelay.
--   processed_events : durable idempotency for the monolith's order-notification consumer.
-- Additive only. Safe to re-run.
--
--   docker exec -i quickkart-postgres psql -U postgres -d quickkart -v ON_ERROR_STOP=1 < infrastructure/postgres/migrations/005_kafka_outbox_and_idempotency.sql
CREATE TABLE IF NOT EXISTS outbox_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     VARCHAR(120) NOT NULL UNIQUE,
    topic        VARCHAR(200) NOT NULL,
    message_key  VARCHAR(200),
    payload      TEXT         NOT NULL,
    created_at   TIMESTAMP    NOT NULL,
    published_at TIMESTAMP,
    attempts     INTEGER      NOT NULL DEFAULT 0,
    last_error   VARCHAR(500)
);
-- The relay only ever scans unpublished rows, oldest first.
CREATE INDEX IF NOT EXISTS idx_outbox_events_pending ON outbox_events (id) WHERE published_at IS NULL;

CREATE TABLE IF NOT EXISTS processed_events (
    event_id     VARCHAR(120) PRIMARY KEY,
    consumer     VARCHAR(80)  NOT NULL,
    processed_at TIMESTAMP    NOT NULL
);
